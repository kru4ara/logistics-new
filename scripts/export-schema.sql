-- ============================================================
-- Выгрузка СХЕМЫ (без данных) схемы public в виде SQL-команд.
-- Замена `supabase db dump` / `pg_dump --schema-only`, когда нет Docker.
--
-- Как пользоваться:
--   Supabase → SQL Editor → вставить запрос → Run →
--   над результатом: Export → Download CSV → прислать файл.
--
-- Результат — одна строка: statements (сколько команд) и schema_sql
-- (все команды в порядке применения). Только чтение, ничего не меняет.
-- Таблицы bak_* (ручные бэкапы) пропускаются.
--
-- Проверено: база, собранная из выгрузки, совпадает с исходной по
-- pg_dump (кроме GRANT USAGE ON SCHEMA — Supabase выдаёт сам), и на ней
-- проходят все проверки supabase/tests/rls_policies.test.sql.
-- ============================================================
with
tbl as (
  select c.oid, c.relname
  from pg_class c
  where c.relnamespace = 'public'::regnamespace
    and c.relkind in ('r', 'p')
    and c.relname not like 'bak\_%'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
parts as (
  -- 0. Шапка
  select 0 as ord, '' as k, 'set check_function_bodies = off;' as ddl

  -- 1. Расширения
  union all
  select 1, e.extname,
         format('create extension if not exists %I with schema %I;', e.extname, n.nspname)
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname <> 'plpgsql'

  -- 2. Перечисления (enum)
  union all
  select 2, t.typname,
         format('create type public.%I as enum (%s);', t.typname,
                (select string_agg(quote_literal(enumlabel), ', ' order by enumsortorder)
                   from pg_enum where enumtypid = t.oid))
  from pg_type t
  where t.typnamespace = 'public'::regnamespace and t.typtype = 'e'

  -- 3. Последовательности (кроме identity — те создаются с колонкой)
  union all
  select 3, s.relname,
         format('create sequence if not exists public.%I;', s.relname)
  from pg_class s
  where s.relnamespace = 'public'::regnamespace and s.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = s.oid and d.deptype = 'i')

  -- 4. Функции (кроме функций расширений)
  union all
  select 4, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
         pg_get_functiondef(p.oid) || ';'
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace
    and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')

  -- 5. Таблицы с колонками
  union all
  select 5, t.relname,
         format(E'create table if not exists public.%I (\n%s\n);', t.relname,
           (select string_agg(
                     format('  %I %s%s%s%s', a.attname,
                            format_type(a.atttypid, a.atttypmod),
                            case a.attidentity
                              when 'a' then ' generated always as identity'
                              when 'd' then ' generated by default as identity'
                              else '' end,
                            case when a.attgenerated = 's'
                                 then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                                 when ad.adbin is not null and a.attidentity = ''
                                 then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
                                 else '' end,
                            case when a.attnotnull then ' not null' else '' end),
                     E',\n' order by a.attnum)
              from pg_attribute a
              left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
              where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from tbl t

  -- 6. Ограничения: первичные, уникальные, check, exclude
  union all
  select 6, t.relname || '.' || c.conname,
         format('alter table public.%I add constraint %I %s;', t.relname, c.conname, pg_get_constraintdef(c.oid))
  from pg_constraint c join tbl t on t.oid = c.conrelid
  where c.contype in ('p', 'u', 'c', 'x')

  -- 7. Внешние ключи (после всех таблиц)
  union all
  select 7, t.relname || '.' || c.conname,
         format('alter table public.%I add constraint %I %s;', t.relname, c.conname, pg_get_constraintdef(c.oid))
  from pg_constraint c join tbl t on t.oid = c.conrelid
  where c.contype = 'f'

  -- 8. Индексы, не созданные ограничениями
  union all
  select 8, i.relname, pg_get_indexdef(i.oid) || ';'
  from pg_index x
  join pg_class i on i.oid = x.indexrelid
  join tbl t on t.oid = x.indrelid
  where not exists (select 1 from pg_constraint c where c.conindid = x.indexrelid)

  -- 9. Представления
  union all
  select 9, v.relname,
         format(E'create or replace view public.%I as\n%s', v.relname, pg_get_viewdef(v.oid))
  from pg_class v
  where v.relnamespace = 'public'::regnamespace and v.relkind = 'v'
    and not exists (select 1 from pg_depend d where d.objid = v.oid and d.deptype = 'e')

  -- 10. Триггеры
  union all
  select 10, t.relname || '.' || g.tgname, pg_get_triggerdef(g.oid) || ';'
  from pg_trigger g join tbl t on t.oid = g.tgrelid
  where not g.tgisinternal

  -- 11. RLS
  union all
  select 11, t.relname,
         format('alter table public.%I enable row level security;', t.relname)
         || case when c.relforcerowsecurity
                 then format(' alter table public.%I force row level security;', t.relname) else '' end
  from tbl t join pg_class c on c.oid = t.oid
  where c.relrowsecurity

  -- 12. Политики RLS (public и storage.objects)
  union all
  select 12, p.schemaname || '.' || p.tablename || '.' || p.policyname,
         format('create policy %I on %I.%I as %s for %s to %s%s%s;',
                p.policyname, p.schemaname, p.tablename, lower(p.permissive), lower(p.cmd),
                (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ')
                   from unnest(p.roles) r),
                case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
                case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end)
  from pg_policies p
  where (p.schemaname = 'public' and p.tablename not like 'bak\_%')
     or (p.schemaname = 'storage' and p.tablename = 'objects')

  -- 13. Права на таблицы и функции для ролей Supabase.
  -- Сначала ОТЗЫВАЕМ всё: Supabase сам выдаёт anon/authenticated права на
  -- новые таблицы и функции, а Postgres — EXECUTE для PUBLIC. Без отзыва
  -- закрытое миграциями (lookup_login_email, login_failures,
  -- driver_telegram_links) в новой базе снова стало бы открытым.
  union all
  select 13, t.relname || '.0',
         format('revoke all on table public.%I from public, anon, authenticated, service_role;', t.relname)
  from tbl t
  union all
  select 13, t.relname || '.' || g.grantee,
         format('grant %s on table public.%I to %I;', g.privs, t.relname, g.grantee)
  from tbl t
  cross join lateral (
    select grantee, string_agg(privilege_type, ', ' order by privilege_type) as privs
    from information_schema.role_table_grants rg
    where rg.table_schema = 'public' and rg.table_name = t.relname
      and rg.grantee in ('anon', 'authenticated', 'service_role')
    group by grantee
  ) g
  union all
  select 14, p.proname || '.0',
         format('revoke all on function public.%I(%s) from public, anon, authenticated, service_role;',
                p.proname, pg_get_function_identity_arguments(p.oid))
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  -- EXECUTE для PUBLIC — только там, где он есть на исходной базе
  select 14, p.proname || '.1',
         format('grant execute on function public.%I(%s) to public;',
                p.proname, pg_get_function_identity_arguments(p.oid))
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
    and (p.proacl is null or exists (select 1 from aclexplode(p.proacl) a where a.grantee = 0 and a.privilege_type = 'EXECUTE'))
  union all
  select 14, r.routine_name || '.' || r.grantee,
         format('grant execute on function public.%I(%s) to %I;', p.proname,
                pg_get_function_identity_arguments(p.oid), r.grantee)
  from information_schema.role_routine_grants r
  join pg_proc p on p.proname = r.routine_name and p.pronamespace = 'public'::regnamespace
  where r.routine_schema = 'public' and r.grantee in ('anon', 'authenticated', 'service_role')
    and r.privilege_type = 'EXECUTE'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')

  -- 15. Бакеты Storage
  union all
  select 15, b.id,
         format('insert into storage.buckets (id, name, public) values (%L, %L, %s) on conflict (id) do nothing;',
                b.id, b.name, b.public::text)
  from storage.buckets b

  -- 16. Комментарии к таблицам, колонкам, функциям, ограничениям
  union all
  select 16, t.relname, format('comment on table public.%I is %L;', t.relname, obj_description(t.oid, 'pg_class'))
  from tbl t where obj_description(t.oid, 'pg_class') is not null
  union all
  select 16, t.relname || '.' || a.attname,
         format('comment on column public.%I.%I is %L;', t.relname, a.attname, col_description(t.oid, a.attnum))
  from tbl t join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  where col_description(t.oid, a.attnum) is not null
  union all
  select 16, p.proname,
         format('comment on function public.%I(%s) is %L;', p.proname,
                pg_get_function_identity_arguments(p.oid), obj_description(p.oid, 'pg_proc'))
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace and obj_description(p.oid, 'pg_proc') is not null
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  select 16, t.relname || '.' || c.conname,
         format('comment on constraint %I on public.%I is %L;', c.conname, t.relname, obj_description(c.oid, 'pg_constraint'))
  from pg_constraint c join tbl t on t.oid = c.conrelid
  where obj_description(c.oid, 'pg_constraint') is not null
)
-- Одна строка: редактор может ограничивать число строк результата,
-- и часть схемы потерялась бы молча.
select count(*) as statements,
       string_agg(ddl, E'\n\n' order by ord, k) as schema_sql
from parts;
