-- Удаление признака «расходы сведены» (costs_closed).
--
-- Признак был введён как ручной фильтр: заказ попадал в статистику,
-- только если по нему сведены расходы. На практике это приводило к
-- тому, что оплаченные заказы (статус paid/invoiced) молча выпадали
-- из статистики, и счётчики рейсов/экспедирований не сходились с
-- фактом (октябрь 2026: показывало 6 экспедирований вместо 7 —
-- заказ 30Е не был сведен, хотя был выставлен счёт).
--
-- Признак признан лишним и удаляется полностью:
--   - заказ завершён, если его статус paid или invoiced;
--   - в статистику он идёт по дате выгрузки (рейс — финиш,
--     экспедирование — разгрузка).
--
-- Миграция безопасна: в базе нет ни функций, ни триггеров, ни
-- политик, которые используют costs_closed. Код приложения
-- обращается к колонке только на создании заказа — он уже не
-- пишет это поле (см. app/geocode-actions.ts).

alter table public.trips drop column if exists costs_closed;
