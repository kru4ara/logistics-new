-- 042: наличные из выписки (банкомат, выдача людям) — не общий расход.
--
-- Снятие наличных переводит деньги в кассу/водителю; расход — когда их потратят
-- (расходы рейса). Строки «Общих расходов», созданные из таких операций, давали двойной
-- счёт. Операция остаётся «сопоставлена» с пометкой «наличные». Только правка данных.

delete from public.fixed_costs
 where bank_transaction_id in (
   select id from public.bank_transactions where overhead_category = 'cash'
 );
